/**
 * 证券类型识别工具
 *
 * 根据代码前缀判断是否为场内基金（ETF / LOF / 货币基金等）。
 * 场内基金交易价格精确到厘（3 位小数），且免印花税、免过户费，佣金通常免最低 5 元。
 *
 * 基金前缀规则：
 * - 5[01268]xxx：上交所基金（50 LOF/封闭、51 ETF、52 货币、56 行业ETF、58 科创板ETF）
 * - 1[568]xxx：深交所基金（15/16 ETF·LOF、18 封闭式基金）
 * A 股股票代码以 60/68(沪)、00/30(深) 开头，不会与本规则冲突。
 */
export function isFund(stockCode: string): boolean {
  return /^(5[01268]|1[568])/.test(stockCode);
}
